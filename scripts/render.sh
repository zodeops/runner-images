#!/usr/bin/env bash
# Renders images/<line>/Dockerfile from images/<line>/Dockerfile.in.
#
# Zode refuses COPY and ADD, so the software report cannot be copied into an
# image. The line @SOFTWARE_REPORT_STEP@ in a template becomes a RUN step
# that writes scripts/software-report.sh to /usr/local/bin/zode-software-report.
# The rendered Dockerfiles are committed; edit the templates and run this.
#
#   scripts/render.sh          write every Dockerfile
#   scripts/render.sh --check  fail if a Dockerfile is stale or breaks a Zode limit
set -euo pipefail

cd "$(dirname "$0")/.."
REPORT=scripts/software-report.sh
STEP_MARK=ZODE_STEP
FILE_MARK=ZODE_SOFTWARE_REPORT

# Zode's limits for a Dockerfile (docs/custom-images.md in zodeops/zoded).
MAX_BYTES=$((64 * 1024))
MAX_STEP_BYTES=$((16 * 1024))
MAX_STEPS=200

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

if grep -qxE "[[:space:]]*($STEP_MARK|$FILE_MARK)[[:space:]]*" "$REPORT"; then
  echo "$REPORT has a line that would end a heredoc ($STEP_MARK or $FILE_MARK)" >&2
  exit 1
fi

render() { # TEMPLATE
  local line
  printf '# Generated by scripts/render.sh from %s. Edit that file, not this one.\n' "$1"
  while IFS= read -r line || [ -n "$line" ]; do
    if [ "$line" = "@SOFTWARE_REPORT_STEP@" ]; then
      printf '# The software report (scripts/software-report.sh), installed as\n'
      printf '# /usr/local/bin/zode-software-report.\n'
      printf "RUN <<'%s'\n" "$STEP_MARK"
      printf 'set -euo pipefail\n'
      printf "cat > /usr/local/bin/zode-software-report <<'%s'\n" "$FILE_MARK"
      cat "$REPORT"
      printf '%s\n' "$FILE_MARK"
      printf 'chmod 0755 /usr/local/bin/zode-software-report\n'
      printf '%s\n' "$STEP_MARK"
    else
      printf '%s\n' "$line"
    fi
  done <"$1"
}

# limits FILE: Zode's size and step limits.
limits() {
  local bytes steps big
  bytes=$(wc -c <"$1" | tr -d ' ')
  if [ "$bytes" -gt "$MAX_BYTES" ]; then
    echo "$1: $bytes bytes, Zode takes at most $MAX_BYTES" >&2
    return 1
  fi
  # Instructions are lines starting with a keyword outside heredoc bodies.
  steps=$(awk -v q="'" -v m="$STEP_MARK" '
    inbody { if ($0 == m) inbody = 0; next }
    /^[A-Z]+[ \t]/ { n++; if (index($0, "<<" q m q)) inbody = 1 }
    END { print n + 0 }' "$1")
  if [ "$steps" -gt "$MAX_STEPS" ]; then
    echo "$1: $steps instructions, Zode takes at most $MAX_STEPS" >&2
    return 1
  fi
  big=$(awk -v q="'" -v m="$STEP_MARK" -v max="$MAX_STEP_BYTES" '
    inbody { if ($0 == m) { if (size > max) print start ": " size " bytes"; inbody = 0 } else size += length($0) + 1; next }
    /^RUN / { if (index($0, "<<" q m q)) { inbody = 1; size = 0; start = NR } else if (length($0) > max) print NR ": " length($0) " bytes" }
  ' "$1")
  if [ -n "$big" ]; then
    echo "$1: RUN steps over $MAX_STEP_BYTES bytes (line: size): $big" >&2
    return 1
  fi
}

status=0
found=0
for tpl in images/*/Dockerfile.in; do
  [ -e "$tpl" ] || continue
  found=1
  out=${tpl%.in}
  tmp=$(mktemp)
  render "$tpl" >"$tmp"
  if [ "$mode" = check ]; then
    if ! cmp -s "$tmp" "$out"; then
      echo "$out is stale: run scripts/render.sh and commit the result" >&2
      diff -u "$out" "$tmp" >&2 || true
      status=1
    fi
    limits "$out" || status=1
    rm -f "$tmp"
  else
    mv "$tmp" "$out"
    chmod 0644 "$out"
    limits "$out" || status=1
    echo "wrote $out"
  fi
done

if [ "$found" = 0 ]; then
  echo "no images/*/Dockerfile.in found" >&2
  exit 1
fi
exit "$status"
